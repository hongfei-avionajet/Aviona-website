function applyCopyrightNotice(html) {
  let next = html
    .replaceAll(" © 2026 AVIONA. All rights reserved.", "")
    .replace(
      '<img src="/assets/is-bao-certificate.jpg" alt="IS-BAO certificate of registration for Avion Infinity Group Limited">',
      '<img src="/assets/is-bao-certificate.jpg" alt="IS-BAO certificate of registration for Avion Infinity Group Limited" data-i18n-alt="a11y.isbaoCertificate">',
    );

  if (!next.includes('data-i18n="ftr.professionalNotice"')) {
    const legalStart = next.lastIndexOf('<div class="legal">');
    const noticeStart = legalStart >= 0
      ? next.indexOf('<p style="margin-bottom: 14px;">', legalStart)
      : -1;
    if (noticeStart >= 0) {
      const noticeEnd = next.indexOf("</p>", noticeStart);
      if (noticeEnd >= 0) {
        const professionalNotice = `<p class="professional-notice" data-i18n="ftr.professionalNotice">${english("ftr.professionalNotice")}</p>`;
        next = `${next.slice(0, noticeStart)}${professionalNotice}${next.slice(noticeEnd + 4)}`;
      }
    }
  }

  if (next.includes('class="copyright-notice"')) return next;

  const legalStart = next.lastIndexOf('<div class="legal">');
  if (legalStart < 0) return next;

  const footerEnd = next.indexOf("</footer>", legalStart);
  if (footerEnd < 0) return next;

  const legalClose = next.lastIndexOf("</div>", footerEnd);
  if (legalClose < legalStart) return next;

  const notice = `  <p class="copyright-notice" data-i18n="ftr.copyrightNotice">${english("ftr.copyrightNotice")}</p>\n`;
  return `${next.slice(0, legalClose)}${notice}${next.slice(legalClose)}`;
}

function normalizeRouteKey(routeKey) {
  const key = String(routeKey ?? "")
    .split("?")[0]
    .split("#")[0]
    .replace(/^\/+|\/+$/g, "");

  if (key === "ways-to-participate") return "ways";
  return key || "home";
}

/**
 * Applies the approved content overlay. Safe to call repeatedly.
 */
export function applyApprovedContent2026(routeKey, html) {
  if (typeof html !== "string" || html.length === 0) return html;

  const normalizedRoute = normalizeRouteKey(routeKey);
  let next = html;

  if (normalizedRoute === "home") next = applyHomeContent(next);
  if (normalizedRoute === "why") next = applyWhyContent(next);
  if (normalizedRoute === "ways") next = applyWaysContent(next);
  if (normalizedRoute === "aircraft") next = applyAircraftContent(next);
  if (normalizedRoute === "about") next = applyAboutContent(next);
  if (normalizedRoute === "contact") next = applyContactContent(next);

  // Send every Contact Us entry point to the preferred-channels section.
  next = next
    .replace(/#contact-form\b/g, "#contact-channels")
    .replace(/href="\/contact"(?![?#])/g, 'href="/contact#contact-channels"');

  return applyCopyrightNotice(next);
}
