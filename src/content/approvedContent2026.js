function replaceBetween(html, startMarker, endMarker, replacement) {
  const start = html.indexOf(startMarker);
  if (start < 0) return html;

  const end = html.indexOf(endMarker, start + startMarker.length);
  if (end < 0) return html;

  return `${html.slice(0, start)}${replacement}${html.slice(end)}`;
}

function replaceElementByI18nKey(html, key, replacement) {
  const marker = `data-i18n="${key}"`;
  const markerIndex = html.indexOf(marker);
  if (markerIndex < 0) return html;

  const openStart = html.lastIndexOf("<", markerIndex);
  const openEnd = html.indexOf(">", markerIndex + marker.length);
  if (openStart < 0 || openEnd < 0) return html;

  const tagName = html.slice(openStart + 1, openEnd).match(/^([a-z][\w-]*)/i)?.[1];
  if (!tagName) return html;

  const closeTag = `</${tagName}>`;
  const closeStart = html.indexOf(closeTag, openEnd + 1);
  if (closeStart < 0) return html;

  return `${html.slice(0, openStart)}${replacement}${html.slice(closeStart + closeTag.length)}`;
}

